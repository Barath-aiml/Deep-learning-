def assess_priority(verified, confirmed_count, safety_concern, traffic_exposure):
    # Transparent, rule-based triage. Not an engineering severity model.
    if not verified:
        return (
            "Pending verification",
            "The user has not confirmed the image and damage."
        )
    if confirmed_count == 0:
        return (
            "No damage confirmed",
            "The user confirmed zero damaged regions. Reinspect if uncertain."
        )
    if safety_concern and traffic_exposure:
        return (
            "High preliminary priority",
            "User confirmed damage, a safety concern, and heavy traffic exposure."
        )
    if safety_concern or traffic_exposure or confirmed_count >= 3:
        reasons = []
        if safety_concern:
            reasons.append("a reported safety concern")
        if traffic_exposure:
            reasons.append("reported heavy traffic exposure")
        if confirmed_count >= 3:
            reasons.append("three or more user-confirmed damaged regions")
        return (
            "Medium preliminary priority",
            "Rule triggered by " + ", ".join(reasons) + "."
        )
    return (
        "Lower preliminary priority",
        "Damage was user-confirmed, with no reported safety concern or heavy traffic exposure."
    )


